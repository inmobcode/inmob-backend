def localize(message: str, locale: str) -> str:
    index = LOCALES.index(locale)
    known = EXACT.get(message)
    if known:
        return known[index]
    for pattern, templates in PATTERNS:
        match = pattern.match(message)
        if match:
            return templates[index].format(*match.groups())
    return import_messages.localize(message, locale) or message


def _leaves(value, locale: str):
    if isinstance(value, str):
        return localize(value, locale)
    if isinstance(value, list):
        return [_leaves(item, locale) for item in value]
    if isinstance(value, dict):
        return {key: _leaves(item, locale) for key, item in value.items()}
    return value


def localize_payload(payload, locale: str):
    """Rewrites the strings of an error body: `message`, and every leaf of `errors`."""
    if not isinstance(payload, dict):
        return payload
    out = dict(payload)
    if isinstance(out.get("message"), str):
        out["message"] = localize(out["message"], locale)
    if "errors" in out:
        out["errors"] = _leaves(out["errors"], locale)
    return out
