def field_label(key: str, label: str, locale: str) -> str:
    labels = FIELD_LABELS.get(key)
    return labels[LOCALES.index(locale)] if labels else label


def _part(value: str, locale: str) -> str:
    """A field name inside a message ("Precio: «x» no es un número")."""
    key = _LABEL_KEY.get(value)
    return field_label(key, value, locale) if key else value


def localize(message: str, locale: str) -> str | None:
    """The message in `locale`, or None if it isn't one of the importer's."""
    index = LOCALES.index(locale)
    known = EXACT.get(message)
    if known:
        return known[index]
    for pattern, templates in PATTERNS:
        match = pattern.match(message)
        if match:
            return templates[index].format(*(_part(group, locale) for group in match.groups()))
    return None


def _each(messages: list, locale: str) -> list:
    return [localize(m, locale) or m if isinstance(m, str) else m for m in messages]


def localize_plan(payload: dict, locale: str) -> dict:
    """A preview or an import result with its warnings and errors in `locale`."""
    out = dict(payload)
    if isinstance(out.get("warnings"), list):
        out["warnings"] = _each(out["warnings"], locale)
    if isinstance(out.get("rows"), list):
        out["rows"] = [
            {**row, "warnings": _each(row.get("warnings", []), locale), "errors": _each(row.get("errors", []), locale)}
            for row in out["rows"]
        ]
    if isinstance(out.get("failures"), list):
        out["failures"] = [
            {**f, "error": localize(f["error"], locale) or f["error"]} if isinstance(f.get("error"), str) else f
            for f in out["failures"]
        ]
    return out
